"""Maintainer side: turn "this AOI needs imagery" into per-tile DataLoader
configs, one per tile the library does not already hold.

A project never writes its own acquisition settings: the product spec
(PRODUCT.yaml) supplies them, the library supplies output.dir, and tiles
already in the library are reported, not acquired again. Re-running the
config of a tile that *is* held is how it gets newly published
observations (DataLoader resumes; nothing already acquired is re-downloaded).
"""
from __future__ import annotations

from pathlib import Path
from typing import Optional

import yaml

from imagery_library.grids import grid_system_of, tiles_for_aoi
from imagery_library.layout import Library, LibraryError, Product
from imagery_library.query import read_aoi


def tiles_needed(lib: Library, product: Product, *, aoi=None, tiles: Optional[list] = None) -> list[dict]:
    """[{grid_system, tile, aoi_share, held}] for an AOI or explicit tile ids."""
    held = {(g, t) for g, t, _ in product.tiles()}
    out = []
    if aoi is not None:
        geom = read_aoi(aoi)
        for system in product.grid_systems:
            found = tiles_for_aoi(system, geom)
            if found is None:
                raise LibraryError(f"{product.key}: no tile helper for grid system {system!r}; list tiles explicitly")
            out += found
    for t in tiles or []:
        out.append({"grid_system": grid_system_of(t, product.grid_systems), "tile": t, "aoi_share": None})
    seen, uniq = set(), []
    for r in out:
        k = (r["grid_system"], r["tile"])
        if k not in seen:
            seen.add(k)
            uniq.append({**r, "held": k in held})
    return uniq


def write_configs(lib: Library, product: Product, needed: list[dict], out_dir, *, include_held: bool = False) -> list[Path]:
    """One DataLoader config per tile (missing tiles; plus held ones with
    include_held, which is how a maintainer updates them)."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for r in needed:
        if r["held"] and not include_held:
            continue
        cfg = product.config_for_tile(r["tile"], r["grid_system"])
        name = f"{product.name}_{product.version}_{r['grid_system']}_{r['tile']}.yaml"
        header = (f"# Generated by imagery-library from {product.key} PRODUCT.yaml -- do not edit; change the product.\n"
                  f"# {'update of a held tile' if r['held'] else 'new tile'}: {r['grid_system']}/{r['tile']}\n"
                  f"#   data-loader run {name}\n")
        p = out_dir / name
        p.write_text(header + yaml.safe_dump(cfg, sort_keys=False))
        written.append(p)
    return written
